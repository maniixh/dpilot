import {
  containerName,
  engineSpec,
  HEALTHCHECK_TIMING,
  type InstanceSettings,
  imageRef,
  volumeName,
} from "./engine-specs.ts";

/** A JSON string is a valid YAML double-quoted scalar; `$$` stops compose interpolation. */
function q(value: string): string {
  return JSON.stringify(value.replaceAll("$", "$$$$"));
}

function seconds(ns: number): string {
  return `${ns / 1_000_000_000}s`;
}

/** docker-compose.yml that recreates the instance on the same named volume. */
export function composeYaml(settings: InstanceSettings): string {
  const spec = engineSpec(settings.engine);
  const env = spec.env(settings).map((entry) => {
    const eq = entry.indexOf("=");
    return `      ${entry.slice(0, eq)}: ${q(entry.slice(eq + 1))}`;
  });
  const test = `[${spec.healthcheck.map(q).join(", ")}]`;

  return [
    `# Generated by Dpilot for the instance "${settings.name}".`,
    "# Stop or remove the Dpilot-managed container first; both use the same name, port and volume.",
    "services:",
    `  ${settings.name}:`,
    `    image: ${q(imageRef(settings.engine, settings.version))}`,
    `    container_name: ${q(containerName(settings.name))}`,
    "    environment:",
    ...env,
    "    ports:",
    `      - ${q(`127.0.0.1:${settings.port}:${spec.containerPort}`)}`,
    "    volumes:",
    `      - ${q(`data:${spec.dataPath(settings.version)}`)}`,
    "    healthcheck:",
    `      test: ${test}`,
    `      interval: ${seconds(HEALTHCHECK_TIMING.Interval)}`,
    `      timeout: ${seconds(HEALTHCHECK_TIMING.Timeout)}`,
    `      retries: ${HEALTHCHECK_TIMING.Retries}`,
    `      start_period: ${seconds(HEALTHCHECK_TIMING.StartPeriod)}`,
    "volumes:",
    "  data:",
    `    name: ${q(volumeName(settings.name))}`,
    "",
  ].join("\n");
}
