/**
 * Renders a TypeScript module that embeds every built web file into the compiled binary
 * and exports a manifest mapping URL paths ("/assets/app.js") to embedded file paths.
 */
export function renderAssetModule(files: readonly string[], importBase: string): string {
  const urlPaths = files.map((file) => file.replaceAll("\\", "/"));
  if (!urlPaths.includes("index.html")) {
    throw new Error("Web build is missing index.html");
  }

  const imports = urlPaths.map(
    (path, i) =>
      `import f${i} from ${JSON.stringify(`${importBase}/${path}`)} with { type: "file" };`,
  );
  const entries = urlPaths.map((path, i) => `  ${JSON.stringify(`/${path}`)}: f${i},`);

  return [
    "// Generated by scripts/compile.ts. Do not edit.",
    ...imports,
    "",
    "export const webAssets: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}
